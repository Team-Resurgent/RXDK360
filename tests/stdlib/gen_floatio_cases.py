#!/usr/bin/env python3
"""
Generate floatio_cases.h for t_floatio.c: printf conversions of doubles and the
exact, correctly rounded output C requires (Python's % formatting rounds the
exact binary value to nearest, ties to even, as glibc and MSVC do).

The cases cover both of libc's paths: up to 17 significant digits (the Ryu
dtoa engine) and past 17 (dtoa_big.c), for e, f and g conversions of random
bit patterns, decimal-looking values, exact ties, carries into a new leading
digit, denormals and the extremes. The seed is fixed, so the header only
changes when this script does.

Usage: python gen_floatio_cases.py   (rewrites floatio_cases.h next to it)
Shared by both consoles' suites; copy both files together.
"""
import math
import os
import random
import struct

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "floatio_cases.h")
MAX_LEN = 160  # longest expected string kept in the table


def bits(x):
    return struct.unpack("<Q", struct.pack("<d", x))[0]


def from_bits(b):
    return struct.unpack("<d", struct.pack("<Q", b))[0]


def values(rng):
    v = [0.1, 1 / 3, 2.675, 0.5, 1.5, 2.5, 0.125, 0.375, 9.5, 99.5, 0.95, 0.995,
         999999.5, 9.999999999999999e22, 1e22, 1e23, 2.0 ** 63 * 1.5, 2.0 ** 53 + 2,
         5e-324, 2.2250738585072014e-308, 2.2250738585072009e-308,
         1.7976931348623157e308, 1e-300, 123456789012345678901234567890.0,
         -0.1, -2.5, -5e-324]
    while len(v) < 120:
        x = from_bits(rng.getrandbits(64))
        if math.isfinite(x):
            v.append(x)
    for _ in range(60):
        v.append(rng.randint(-10 ** 7, 10 ** 7) / rng.choice([2, 4, 8, 16, 1024]))  # exact ties
        v.append(round(rng.uniform(-1e6, 1e6), rng.randint(0, 6)))                 # decimal-looking
        v.append(from_bits(rng.getrandbits(52)))                                    # denormals
    return v


def cases():
    rng = random.Random(0x5EED)
    out = []
    for x in values(rng):
        for _ in range(3):
            conv = rng.choice("efg")
            # Half the precisions stay within the 17 digits Ryu produces, half go past.
            prec = rng.randint(0, 16) if rng.random() < 0.5 else rng.randint(17, 45)
            fmt = "%%.%d%s" % (prec, conv)
            want = fmt % x
            if len(want) <= MAX_LEN:
                out.append((bits(x), fmt, want))
    return out


def main():
    rows = cases()
    with open(OUT, "w", newline="\n") as f:
        f.write("/* Generated by gen_floatio_cases.py; do not edit. */\n")
        f.write("static const struct floatio_case {\n")
        f.write("    unsigned long long bits; /* the double's IEEE-754 encoding */\n")
        f.write("    const char *fmt;\n")
        f.write("    const char *want;\n")
        f.write("} floatio_cases[] = {\n")
        for b, fmt, want in rows:
            f.write('    { 0x%016xull, "%s", "%s" },\n' % (b, fmt, want))
        f.write("};\n")
    print("wrote %d cases to %s" % (len(rows), OUT))


if __name__ == "__main__":
    main()
